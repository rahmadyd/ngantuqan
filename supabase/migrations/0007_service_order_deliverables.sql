-- =============================================================================
-- ngantuqan — 0007: service order deliverables
--
-- Spec deviation, documented before the code that deviates exists.
--
-- §4.J lists "Required deliverables" as a field of the project brief form,
-- but §6's `service_orders` column list has no column to hold it. The brief
-- cannot be captured faithfully without somewhere to put it, so this
-- migration adds one nullable text column.
--
-- Nothing else changes: no column is renamed, no type is altered, and the
-- existing policies and triggers are untouched. `service_orders` therefore
-- differs from §6 by exactly one additional nullable column.
-- =============================================================================

ALTER TABLE public.service_orders
  ADD COLUMN IF NOT EXISTS requested_deliverables text;

COMMENT ON COLUMN public.service_orders.requested_deliverables IS
  'Deliverables the client asks for beyond the package scope (spec §4.J).';

-- ---------------------------------------------------------------------------
-- record_service_order — the only path that creates a service order.
--
-- The order number is generated by the trigger (trg_service_orders_number);
-- the client never supplies one, which is why the insert lives here instead
-- of in the Server Action. The function also re-checks that the service and
-- the package are available, so a stale form cannot create an order against
-- something that was retired in the meantime.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.record_service_order(p_brief jsonb)
RETURNS TABLE (id uuid, order_number text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id uuid;
  v_number text;
  v_service uuid := (p_brief ->> 'service_id')::uuid;
  v_package uuid := NULLIF(p_brief ->> 'package_id', '')::uuid;
BEGIN
  IF v_service IS NULL THEN
    RAISE EXCEPTION 'A service is required';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.services
     WHERE public.services.id = v_service AND public.services.is_active
  ) THEN
    RAISE EXCEPTION 'Service not available';
  END IF;

  IF v_package IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.service_packages
     WHERE public.service_packages.id = v_package
       AND public.service_packages.service_id = v_service
       AND public.service_packages.is_active
  ) THEN
    RAISE EXCEPTION 'Package not available';
  END IF;

  INSERT INTO public.service_orders (
    customer_id,
    customer_name,
    customer_email,
    service_id,
    package_id,
    project_description,
    target_audience,
    design_references,
    preferred_colors,
    requested_deliverables,
    budget,
    deadline,
    order_status,
    payment_status
  )
  VALUES (
    NULLIF(p_brief ->> 'customer_id', '')::uuid,
    p_brief ->> 'customer_name',
    p_brief ->> 'customer_email',
    v_service,
    v_package,
    p_brief ->> 'project_description',
    NULLIF(p_brief ->> 'target_audience', ''),
    NULLIF(p_brief ->> 'design_references', ''),
    NULLIF(p_brief ->> 'preferred_colors', ''),
    NULLIF(p_brief ->> 'requested_deliverables', ''),
    NULLIF(p_brief ->> 'budget', '')::numeric,
    NULLIF(p_brief ->> 'deadline', '')::date,
    'NEW_INQUIRY',
    'PENDING'
  )
  RETURNING public.service_orders.id, public.service_orders.order_number
    INTO v_id, v_number;

  RETURN QUERY SELECT v_id, v_number;
END;
$$;
